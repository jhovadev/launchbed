import { mkdtempSync, readFileSync, rmSync, statSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { describe, expect, test } from "bun:test";
import {
  GENERATED_MISE,
  createPlan,
  generateProject,
  materializeProject,
  mergeTooling,
  readZip,
  writeProjectTree,
} from "@android-initializr/generator";
import { InitializrError } from "@android-initializr/schema";
import { baseRequest, stableAddon } from "./fixtures";
import { allFixtureAddons, fixtureFragments } from "./fixtures-addons";

const fragments = {
  ...fixtureFragments,
  "test/fragment.txt": "trusted fixture fragment\n",
};

function textFrom(files: Map<string, Uint8Array>, path: string): string {
  return new TextDecoder().decode(files.get(path));
}

const rustTooling = {
  tools: [{ name: "rust", version: "1.85.0" }],
  env: [],
  justRecipes: [
    {
      name: "ffi-build",
      description: "Build the native library",
      lines: ["cargo build --release"],
      dependencies: [],
    },
  ],
};

describe("mise and just tooling", () => {
  test("base projects get pinned tools and just shortcuts", () => {
    const { files } = materializeProject(baseRequest());
    const mise = textFrom(files, "mise.toml");
    expect(mise).toContain(`min_version = "${GENERATED_MISE.minVersion}"`);
    expect(mise).toContain(`java = "${GENERATED_MISE.tools.java}"`);
    expect(mise).toContain(`just = "${GENERATED_MISE.tools.just}"`);
    expect(mise).toContain("run = \"just doctor\"");
    expect(mise).toContain("run = \"just build\"");
    expect(mise).toContain("ANDROID_HOME");
    expect(mise).not.toMatch(/SECRET|TOKEN|PASSWORD|KEYSTORE/);

    const justfile = textFrom(files, "justfile");
    expect(justfile).toContain("# Generated by Launchbed.");
    expect(justfile).toContain("# @initializr-slot just-recipes");
    expect(justfile).toMatch(/^doctor:/m);
    expect(justfile).toMatch(/^build:/m);
    expect(justfile).toMatch(/^test:/m);
    expect(justfile).toMatch(/^run:/m);
  });

  test("addons contribute tools and recipes deterministically", () => {
    const addon = stableAddon("native/fixture-ffi", {
      tooling: rustTooling,
      fileOperations: [{ type: "add", path: "addons/ffi.txt", template: "fixtures/screen" }],
    });
    const first = materializeProject(baseRequest({ addons: ["native/fixture-ffi"] }), {
      addons: [addon],
      fragments,
    });
    const second = materializeProject(baseRequest({ addons: ["native/fixture-ffi"] }), {
      addons: [addon],
      fragments,
    });
    expect(textFrom(first.files, "mise.toml")).toBe(textFrom(second.files, "mise.toml"));
    expect(textFrom(first.files, "justfile")).toBe(textFrom(second.files, "justfile"));
    expect(textFrom(first.files, "mise.toml")).toContain('rust = "1.85.0"');
    const justfile = textFrom(first.files, "justfile");
    expect(justfile).toContain("ffi-build:");
    expect(justfile).toContain("cargo build --release");
    expect(justfile).toContain("Contributed by native/fixture-ffi");
    const slotIndex = justfile.indexOf("# @initializr-slot just-recipes");
    expect(justfile.indexOf("ffi-build:")).toBeLessThan(slotIndex);
  });

  test("rejects incompatible tool versions and conflicting recipe bodies", () => {
    const left = stableAddon("native/fixture-a", {
      tooling: rustTooling,
      fileOperations: [{ type: "add", path: "addons/a.txt", template: "fixtures/screen" }],
    });
    const right = stableAddon("native/fixture-b", {
      tooling: {
        tools: [{ name: "rust", version: "1.84.0" }],
        env: [],
        justRecipes: [],
      },
      fileOperations: [{ type: "add", path: "addons/b.txt", template: "fixtures/screen" }],
    });
    expect(() => mergeTooling([left, right])).toThrow(InitializrError);
    try {
      mergeTooling([left, right]);
    } catch (error) {
      expect((error as InitializrError).code).toBe("RESOLUTION_ERROR");
      expect((error as Error).message).toContain("Incompatible mise tool versions");
    }

    const recipeConflict = stableAddon("native/fixture-c", {
      tooling: {
        tools: [],
        env: [],
        justRecipes: [
          {
            name: "ffi-build",
            description: "Different body",
            lines: ["echo no"],
            dependencies: [],
          },
        ],
      },
      fileOperations: [{ type: "add", path: "addons/c.txt", template: "fixtures/screen" }],
    });
    expect(() => mergeTooling([left, recipeConflict])).toThrow(/Conflicting just recipes/);

    const reserved = stableAddon("tooling/fixture-reserved", {
      tooling: {
        tools: [],
        env: [],
        justRecipes: [
          { name: "build", description: "Nope", lines: ["echo hijack"], dependencies: [] },
        ],
      },
      fileOperations: [{ type: "add", path: "addons/reserved.txt", template: "fixtures/screen" }],
    });
    expect(() => mergeTooling([reserved])).toThrow(/reserved just recipe/);
  });

  test("identical recipe bodies from two addons are deduplicated", () => {
    const first = stableAddon("native/fixture-a", {
      tooling: rustTooling,
      fileOperations: [{ type: "add", path: "addons/a.txt", template: "fixtures/screen" }],
    });
    const second = stableAddon("native/fixture-b", {
      tooling: rustTooling,
      fileOperations: [{ type: "add", path: "addons/b.txt", template: "fixtures/screen" }],
    });
    const merged = mergeTooling([first, second]);
    expect(merged.tools.get("rust")?.version).toBe("1.85.0");
    expect(merged.recipes.get("ffi-build")?.addons).toEqual(["native/fixture-a", "native/fixture-b"]);
  });

  test("rejects secret-like env keys in the schema", () => {
    expect(() =>
      stableAddon("tooling/fixture-secret", {
        tooling: {
          tools: [],
          env: [{ key: "API_TOKEN", value: "nope" }],
          justRecipes: [],
        },
      }),
    ).toThrow();
  });

  test("writeProjectTree writes executables and refuses a non-empty directory", () => {
    const { files } = materializeProject(baseRequest());
    const root = mkdtempSync(join(tmpdir(), "launchbed-tree-"));
    try {
      const directory = writeProjectTree(files, join(root, "app"));
      expect(statSync(join(directory, "gradlew")).mode & 0o111).toBeGreaterThan(0);
      expect(readFileSync(join(directory, "mise.toml"), "utf8")).toContain("java =");
      expect(() => writeProjectTree(files, directory)).toThrow(InitializrError);
      writeProjectTree(files, directory, { force: true });
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("existing fixture addons still compose with the tooling pass", () => {
    const project = generateProject(baseRequest({ addons: ["ui/fixture-alpha"] }), {
      addons: allFixtureAddons,
      fragments,
    });
    const justfile = new TextDecoder().decode(readZip(project.zip).find((entry) => entry.path === "justfile")!.data);
    expect(justfile).toContain("# @initializr-slot just-recipes");
    expect(createPlan(baseRequest()).files.some((file) => file.path === "mise.toml")).toBe(true);
  });
});
