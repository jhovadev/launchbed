import {
  Hct,
  SchemeExpressive,
  SchemeMonochrome,
  SchemeNeutral,
  SchemeTonalSpot,
  SchemeVibrant,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";
import {
  SEMANTIC_COLOR_KEYS,
  type SemanticColorKey,
  type SemanticColors,
  type ThemeConfig,
} from "@android-initializr/schema";

export type SchemeVariant = ThemeConfig["schemeVariant"];

interface SchemeLike {
  primary: number;
  onPrimary: number;
  primaryContainer: number;
  onPrimaryContainer: number;
  secondary: number;
  onSecondary: number;
  secondaryContainer: number;
  onSecondaryContainer: number;
  tertiary: number;
  onTertiary: number;
  tertiaryContainer: number;
  onTertiaryContainer: number;
  error: number;
  onError: number;
  errorContainer: number;
  onErrorContainer: number;
  background: number;
  onBackground: number;
  surface: number;
  onSurface: number;
  surfaceVariant: number;
  onSurfaceVariant: number;
  outline: number;
  outlineVariant: number;
  inverseSurface: number;
  inverseOnSurface: number;
  inversePrimary: number;
  scrim: number;
  surfaceTint: number;
}

const VARIANTS = {
  tonalSpot: SchemeTonalSpot,
  vibrant: SchemeVibrant,
  expressive: SchemeExpressive,
  neutral: SchemeNeutral,
  monochrome: SchemeMonochrome,
} as const;

function buildScheme(seedColor: string, variant: SchemeVariant, dark: boolean): SemanticColors {
  const Scheme = VARIANTS[variant];
  const scheme = new Scheme(Hct.fromInt(argbFromHex(seedColor)), dark, 0) as unknown as SchemeLike;
  const colors = {} as SemanticColors;
  for (const key of SEMANTIC_COLOR_KEYS) {
    colors[key] = hexFromArgb(scheme[key]).toUpperCase();
  }
  return colors;
}

function applyOverrides(
  base: SemanticColors,
  overrides: Partial<Record<SemanticColorKey, string | undefined>> | undefined,
): SemanticColors {
  if (!overrides) return base;
  const result = { ...base };
  for (const key of SEMANTIC_COLOR_KEYS) {
    const value = overrides[key];
    if (value) result[key] = value.toUpperCase();
  }
  return result;
}

export interface ThemeTokens {
  seedColor: string;
  schemeVariant: SchemeVariant;
  defaultMode: ThemeConfig["defaultMode"];
  light: SemanticColors;
  dark: SemanticColors;
  typography: ThemeConfig["typography"];
  shape: ThemeConfig["shape"];
  spacing: ThemeConfig["spacing"];
  components: ThemeConfig["components"];
}

/**
 * Deterministic Material 3 token resolution. The same function feeds the
 * Compose code generator and the browser preview, so both stay in sync.
 */
export function resolveThemeTokens(theme: ThemeConfig): ThemeTokens {
  const light = applyOverrides(
    buildScheme(theme.seedColor, theme.schemeVariant, false),
    theme.overrides.light,
  );
  const dark = applyOverrides(
    buildScheme(theme.seedColor, theme.schemeVariant, true),
    theme.overrides.dark,
  );
  return {
    seedColor: theme.seedColor.toUpperCase(),
    schemeVariant: theme.schemeVariant,
    defaultMode: theme.defaultMode,
    light,
    dark,
    typography: theme.typography,
    shape: theme.shape,
    spacing: theme.spacing,
    components: theme.components,
  };
}

export function toKotlinColor(hex: string): string {
  return `0xFF${hex.replace("#", "").toUpperCase()}`;
}

function kotlinTokenName(key: SemanticColorKey): string {
  return key.charAt(0).toUpperCase() + key.slice(1);
}

/** Generates `ui/theme/GeneratedColors.kt`. Relative to the Kotlin source root. */
export function generateComposeColors(tokens: ThemeTokens, packageName: string): string {
  const lines: string[] = [
    `package ${packageName}.ui.theme`,
    "",
    "import androidx.compose.ui.graphics.Color",
    "",
    "// Generated by Launchbed from ThemeConfig. Do not edit by hand.",
  ];
  for (const mode of ["Light", "Dark"] as const) {
    const scheme = mode === "Light" ? tokens.light : tokens.dark;
    lines.push("", `// ${mode} scheme (seed ${tokens.seedColor}, ${tokens.schemeVariant})`);
    for (const key of SEMANTIC_COLOR_KEYS) {
      lines.push(`internal val ${mode}${kotlinTokenName(key)} = Color(${toKotlinColor(scheme[key])})`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

/** Generates `ui/theme/GeneratedTokens.kt` (spacing, shape and component tokens). */
export function generateComposeTokens(tokens: ThemeTokens, packageName: string): string {
  const { spacing, shape, components } = tokens;
  const fontFamily =
    tokens.typography.fontFamily === "monospace"
      ? "FontFamily.Monospace"
      : tokens.typography.fontFamily === "serif"
        ? "FontFamily.Serif"
        : tokens.typography.fontFamily === "sansSerif"
          ? "FontFamily.SansSerif"
          : "FontFamily.Default";
  const lines: string[] = [
    `package ${packageName}.ui.theme`,
    "",
    "import androidx.compose.ui.text.font.FontFamily",
    "import androidx.compose.ui.unit.dp",
    "",
    "// Generated by Launchbed from ThemeConfig. Do not edit by hand.",
    `internal val AppFontFamily = ${fontFamily}`,
    `internal val BaseCornerRadius = ${shape.cornerRadius}.dp`,
    "",
    "internal object Spacing {",
    `    val xs = ${spacing.xs}.dp`,
    `    val sm = ${spacing.sm}.dp`,
    `    val md = ${spacing.md}.dp`,
    `    val lg = ${spacing.lg}.dp`,
    `    val xl = ${spacing.xl}.dp`,
    "}",
    "",
    "internal object ComponentTokens {",
    `    val cardCornerRadius = ${components.card.cornerRadius}.dp`,
    `    val cardElevation = ${components.card.elevation}.dp`,
    `    val buttonCornerRadius = ${components.button.cornerRadius}.dp`,
    `    val buttonMinHeight = ${components.button.minHeight}.dp`,
    "}",
    "",
  ];
  return lines.join("\n");
}
