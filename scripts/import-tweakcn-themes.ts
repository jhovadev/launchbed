/**
 * Imports the tweakcn theme presets (https://github.com/jnsahaj/tweakcn, Apache-2.0) into
 * packages/design-tokens/themes/*.json. Run it against a local clone; builds never touch the
 * network because the generated JSON is committed.
 *
 *   git clone https://github.com/jnsahaj/tweakcn /tmp/tweakcn
 *   bun scripts/import-tweakcn-themes.ts --source /tmp/tweakcn          # write
 *   bun scripts/import-tweakcn-themes.ts --source /tmp/tweakcn --check  # verify, no writes
 *
 * Deterministic: presets sorted by id, keys in a fixed order, colors as uppercase sRGB hex.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { convertTweakcnPreset, TWEAKCN_ROLE_MAP, type CssVars } from "../packages/design-tokens/src/tweakcn";
import { SEMANTIC_COLOR_KEYS } from "@launchbed/schema";

const ROOT = resolve(import.meta.dir, "..");
const OUT_DIR = join(ROOT, "packages/design-tokens/themes");
const REPOSITORY = "https://github.com/jnsahaj/tweakcn";
const SOURCE_VARS = [...new Set([...TWEAKCN_ROLE_MAP.map(([, variable]) => variable), "radius", "font-sans"])].sort();

function arg(name: string): string | undefined {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function pick(vars: CssVars): Record<string, string> {
  const out: Record<string, string> = {};
  for (const key of SOURCE_VARS) if (vars[key] !== undefined) out[key] = vars[key]!;
  return out;
}

function ordered<T>(record: Partial<Record<string, T>>, keys: readonly string[]): Record<string, T> {
  const out: Record<string, T> = {};
  for (const key of keys) if (record[key] !== undefined) out[key] = record[key]!;
  return out;
}

export function themeDocument(
  id: string,
  label: string,
  light: CssVars,
  dark: CssVars,
  source: { commit: string; license: string },
): string {
  const theme = convertTweakcnPreset(id, label, light, dark);
  const colors = (roles: typeof theme.light) =>
    ordered(
      Object.fromEntries(Object.entries(roles).map(([role, hex]) => [role, { $type: "color", $value: hex }])),
      SEMANTIC_COLOR_KEYS,
    );
  const document = {
    $schema: "https://tr.designtokens.org/format/",
    $description: `${label}, imported from tweakcn. Generated by scripts/import-tweakcn-themes.ts; do not edit by hand.`,
    id,
    label,
    source: {
      repository: REPOSITORY,
      file: "utils/theme-presets.ts",
      commit: source.commit,
      license: source.license,
      light: pick(light),
      dark: pick(dark),
    },
    color: { light: colors(theme.light), dark: colors(theme.dark) },
    dimension: { shape: { cornerRadius: { $type: "dimension", $value: `${theme.cornerRadius}px` } } },
    fontFamily: { plain: { $type: "fontFamily", $value: theme.fontSans || "system-ui" } },
    $extensions: { "dev.launchbed": { fontFamily: theme.fontFamily, contrastFixes: theme.contrastFixes } },
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}

function indexModule(ids: readonly string[]): string {
  const name = (id: string) => `theme_${id.replace(/[^a-z0-9]/g, "_")}`;
  return [
    "// Generated by scripts/import-tweakcn-themes.ts. Do not edit by hand.",
    ...ids.map((id) => `import ${name(id)} from "./${id}.json";`),
    "",
    "export const TWEAKCN_THEME_FILES = [",
    ...ids.map((id) => `  ${name(id)},`),
    "] as const;",
    "",
  ].join("\n");
}

async function main() {
  const source = arg("--source");
  if (!source || !existsSync(join(source, "utils/theme-presets.ts"))) {
    console.error("Usage: bun scripts/import-tweakcn-themes.ts --source <path to a tweakcn clone> [--check]");
    process.exit(2);
  }
  const license = readFileSync(join(source, "LICENSE"), "utf8");
  if (!/Apache License\s+Version 2\.0/.test(license)) {
    console.error("tweakcn is no longer Apache-2.0; stop and review the license before importing.");
    process.exit(1);
  }
  const commit = execFileSync("git", ["-C", source, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  const { defaultPresets } = (await import(join(resolve(source), "utils/theme-presets.ts"))) as {
    defaultPresets: Record<string, { label: string; styles: { light?: CssVars; dark?: CssVars } }>;
  };
  const config = (await import(join(resolve(source), "config/theme.ts"))) as {
    COMMON_STYLES: readonly string[];
    defaultLightThemeStyles: CssVars;
    defaultDarkThemeStyles: CssVars;
  };
  const expected = new Map<string, string>();
  const ids = Object.keys(defaultPresets).sort();
  for (const id of ids) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) throw new Error(`Unexpected preset id ${id}`);
    const preset = defaultPresets[id]!;
    // Same merge tweakcn applies: defaults, then the preset; shared styles come from light.
    const light: Record<string, string> = { ...config.defaultLightThemeStyles, ...preset.styles.light };
    const dark: Record<string, string> = { ...config.defaultDarkThemeStyles, ...preset.styles.dark };
    for (const key of config.COMMON_STYLES) if (light[key] !== undefined) dark[key] = light[key]!;
    expected.set(`${id}.json`, themeDocument(id, preset.label, light, dark, { commit, license: "Apache-2.0" }));
  }
  expected.set("index.ts", indexModule(ids));
  const check = process.argv.includes("--check");
  const stale = readdirSync(OUT_DIR).filter((name) => !expected.has(name));
  const changed = [...expected].filter(([name, text]) => !existsSync(join(OUT_DIR, name)) || readFileSync(join(OUT_DIR, name), "utf8") !== text);
  if (check) {
    if (changed.length || stale.length) {
      console.error(`tweakcn themes are out of date: ${[...changed.map(([name]) => name), ...stale].join(", ")}`);
      process.exit(1);
    }
    console.log(`tweakcn themes are up to date (${ids.length} presets, commit ${commit.slice(0, 7)}).`);
    return;
  }
  for (const name of stale) rmSync(join(OUT_DIR, name));
  for (const [name, text] of changed) writeFileSync(join(OUT_DIR, name), text);
  console.log(`Imported ${ids.length} tweakcn presets from ${commit.slice(0, 7)} into packages/design-tokens/themes (${changed.length} changed).`);
}

if (import.meta.main) await main();
