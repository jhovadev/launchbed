/**
 * Renders the support matrix in README.md from the catalogs (targets, presets, addons,
 * components), so the README cannot drift. `bun scripts/readme-matrix.ts --write` updates the
 * block between the markers; tests/readme-matrix.test.ts fails when it is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ALL_ADDONS, ALL_PRESETS, buildCatalog } from "@launchbed/catalog";
import { THEME_PRESETS } from "@launchbed/design-tokens";
import { loadComponentCatalog } from "@launchbed/generator";
import { TARGET_IDS, type TargetId } from "@launchbed/schema";

export const MATRIX_START = "<!-- matrix:start (generated by scripts/readme-matrix.ts; do not edit by hand) -->";
export const MATRIX_END = "<!-- matrix:end -->";
const README = join(import.meta.dir, "../README.md");

const SHORT: Record<TargetId, string> = {
  "android-compose": "Compose",
  expo: "Expo",
  flutter: "Flutter",
  "tauri-solid": "Tauri + Solid",
} as Record<TargetId, string>;

function cell(on: boolean): string {
  return on ? "✓" : "—";
}

export function renderReadmeMatrix(): string {
  const catalog = buildCatalog();
  const targets = TARGET_IDS.filter((id) => catalog.targets.some((target) => target.id === id));
  const header = (first: string, extra: string[] = []) =>
    [`| ${[first, ...targets.map((id) => SHORT[id] ?? id), ...extra].join(" | ")} |`, `|${[first, ...targets, ...extra].map(() => "---").join("|")}|`];
  const lines: string[] = [];

  lines.push("**Targets**", "", "| Target | Strategy | Status |", "|---|---|---|");
  for (const target of catalog.targets) {
    const how = target.strategy === "owned" ? "owned (Launchbed writes the whole project)" : `delegate (\`${target.officialCli ?? "official CLI"}\` + Launchbed overlay)`;
    lines.push(`| ${target.displayName} | ${how} | ${target.status} |`);
  }

  lines.push("", "**Presets**", "", ...header("Preset", ["Status"]));
  for (const preset of [...ALL_PRESETS].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(`| \`${preset.id}\` | ${targets.map((id) => cell(preset.targets.includes(id))).join(" | ")} | ${preset.status} |`);
  }

  const generatable = ALL_ADDONS.filter((addon) => addon.status !== "planned").sort((a, b) => a.id.localeCompare(b.id));
  lines.push("", "**Addons**", "", ...header("Addon", ["Status"]));
  for (const addon of generatable) {
    const on = (id: TargetId) => (addon.targets ?? ["android-compose"]).includes(id);
    lines.push(`| \`${addon.id}\` | ${targets.map((id) => cell(on(id))).join(" | ")} | ${addon.status} |`);
  }
  const planned = ALL_ADDONS.filter((addon) => addon.status === "planned").map((addon) => `\`${addon.id}\``).sort();
  lines.push("", `Planned, not generatable yet: ${planned.join(", ")}.`);

  const components = loadComponentCatalog().components;
  lines.push("", "**Registry components** (`launchbed add <name>`)", "", ...header("Component"));
  for (const component of components) {
    lines.push(`| \`${component.name}\` | ${targets.map((id) => cell(component.targets[id]?.status === "supported")).join(" | ")} |`);
  }
  lines.push("", `Themes: ${THEME_PRESETS.length} presets imported from tweakcn (Apache-2.0), usable on every target with \`--theme <id>\`.`);
  return lines.join("\n");
}

export function readmeMatrixBlock(readme: string): string | undefined {
  const start = readme.indexOf(MATRIX_START);
  const end = readme.indexOf(MATRIX_END);
  if (start < 0 || end < start) return undefined;
  return readme.slice(start + MATRIX_START.length, end).trim();
}

if (import.meta.main) {
  const readme = readFileSync(README, "utf8");
  const current = readmeMatrixBlock(readme);
  if (current === undefined) throw new Error("README.md has no matrix markers.");
  const next = renderReadmeMatrix();
  if (process.argv.includes("--write")) {
    const start = readme.indexOf(MATRIX_START) + MATRIX_START.length;
    writeFileSync(README, `${readme.slice(0, start)}\n\n${next}\n\n${readme.slice(readme.indexOf(MATRIX_END))}`);
    console.log("README matrix updated.");
  } else if (current !== next) {
    console.error("README matrix is out of date. Run: bun scripts/readme-matrix.ts --write");
    process.exit(1);
  } else {
    console.log("README matrix is up to date.");
  }
}
